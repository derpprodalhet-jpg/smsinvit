def test_mysql_sms_poll_expiry_cancels_once_without_rebuy(provision):
    s,p,code,iid=provision();provider=CancelCountingProvider();s.client=provider
    sid=s.redeem(code)['id'];expire_number(s,iid)
    with ThreadPoolExecutor(max_workers=32) as pool:results=list(pool.map(lambda _:s.poll(sid),range(100)))
    assert provider.calls==1,'poll expiry must never buy another number'
    assert sum(1 for aid,status in provider.set_status_calls if status==8)==1,'exactly one upstream cancel'
    assert s.db.scalar('SELECT status FROM sms_sessions WHERE id=?',sid)=='CANCELLED'
    assert s.db.scalar('SELECT attempt_count FROM sms_redeem_keys WHERE inventory_item_id=?',iid)==1
    assert s.db.scalar("SELECT COUNT(*) FROM sms_events WHERE session_id=? AND event_type='CANCEL_CONFIRMED'",sid)==1
    # Concurrent reads may observe the in-flight cancel; none may report a fresh acquisition
    # and the stored state must converge without a second upstream call.
    assert all(r['status'] in ('WAITING_CODE','CANCEL_PENDING','CANCELLED') for r in results),{r['status'] for r in results}
    assert all(r['id']==sid and r['attemptCount']==1 for r in results)
    assert s.poll(sid)['status']=='CANCELLED'

