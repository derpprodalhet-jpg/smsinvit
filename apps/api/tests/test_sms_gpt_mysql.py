@pytest.mark.parametrize('mode',['fallback_mobile','both_exhausted'])
def test_mysql_line_monitor_persists_quota_and_reasons_without_refresh_requests(provision,mode):
    from smsinvit.sms.line_type import FreeLineChecker
    from smsinvit.sms.line_monitor import LineCheckMonitor
    s,p,code,iid=provision();p.phone='18325550123';calls=[]
    keys=['sms.line_monitor.numlookupapi','sms.line_monitor.abstractapi']
    old={key:s.db.one('SELECT CAST(value_json AS CHAR) AS valueJson FROM settings WHERE `key`=?',key) for key in keys}
    fake_settings=SimpleNamespace(secret=lambda field:'monitor-test-key')
    def respond(request):
        calls.append(str(request.url.host))
        if request.url.path.endswith('/status'):return httpx.Response(200,json={'quotas':{'month':{'total':100,'remaining':0}}})
        if request.url.host=='api.numlookupapi.com':return httpx.Response(429,json={},headers={'X-RateLimit-Remaining-Quota-Month':'0','X-RateLimit-Limit-Quota-Month':'100'})
        if mode=='both_exhausted':return httpx.Response(429,json={'error':{'message':'Monthly API request limit reached'}})
        return httpx.Response(200,json={'valid':True,'phone':p.phone,'type':'mobile'})
    s.line_checker.close()
    s.line_checker=FreeLineChecker(fake_settings,httpx.Client(transport=httpx.MockTransport(respond)),monitor=s.line_monitor)
    try:
        view=s.redeem(code);assert view['status']=='WAITING_CODE'
        s.on_webhook(p.aid,'123456','simulated');assert s.view(view['id'])['smsCode']=='123456'
        snapshot=LineCheckMonitor(s.db,s.codec).snapshot(fake_settings)
        first,second=snapshot['providers']
        assert first['remaining']==0 and first['total']==100 and first['state']=='quota_exhausted'
        assert second['remaining']==(0 if mode=='both_exhausted' else None)
        assert second['state']==('quota_exhausted' if mode=='both_exhausted' else 'available')
        decision=next(row for row in snapshot['history'] if row['reasons'].get('numlookupapi')=='quota_exhausted')
        assert decision['type']==('LINE_TYPE_SKIPPED' if mode=='both_exhausted' else 'LINE_TYPE_VERIFIED')
        assert decision['reasons']['numlookupapi']=='quota_exhausted'
        assert 'monitor-test-key' not in dumps(snapshot) and 'credentialTag' not in dumps(snapshot)
        for _ in range(3):s.line_monitor.snapshot(fake_settings)
        assert len(calls)==3,'refresh must not query supplier'
        rotated=s.line_monitor.snapshot(SimpleNamespace(secret=lambda field:'new-key'))
        assert all(row['remaining'] is None and row['state']=='not_checked' for row in rotated['providers'])
        s.line_monitor.observe('abstractapi','monitor-test-key',{'state':'quota_exhausted','remaining':0})
        s.line_monitor.observe('abstractapi','monitor-test-key',{'state':'available','cooldownUntil':None})
        assert s.line_monitor.snapshot(fake_settings)['providers'][1]['remaining'] is None
        s.line_monitor.observe('numlookupapi','monitor-test-key',{'state':'checking','remaining':75})
        s.line_monitor.observe('numlookupapi','monitor-test-key',{'state':'available','cooldownUntil':None})
        assert s.line_monitor.snapshot(fake_settings)['providers'][0]['remaining']==75
    finally:
        for key,row in old.items():
            if row:s.db.execute('UPDATE settings SET value_json=CAST(? AS JSON) WHERE `key`=?',row['valueJson'],key)
            else:s.db.execute('DELETE FROM settings WHERE `key`=?',key)


