def test_mysql_two_sms_service_instances_do_not_cancel_a_final_inflight_read(provision):
    s,p,code,iid=provision();entered=threading.Event();release=threading.Event()
    class BlockingProvider(CancelCountingProvider):
        def get_status(self,aid):
            with self.lock:self.get_status_calls+=1
            entered.set();assert release.wait(5)
            return StatusResult('OK','445566','STATUS_OK:445566')
    provider=BlockingProvider();s.client=provider
    sid=s.redeem(code)['id'];expire_number(s,iid)
    peer=SmsService(s.db,s.codec,s.config,client=provider,tokens=s.tokens);peer.catalog=s.catalog
    with ThreadPoolExecutor(max_workers=2) as pool:
        pending=pool.submit(s.poll,sid)
        try:
            assert entered.wait(2)
            result=pool.submit(peer.poll,sid).result(timeout=1)
            assert result['status']=='WAITING_CODE' and provider.get_status_calls==1
            assert not provider.set_status_calls
            with pytest.raises(Error) as error:peer.retry(sid)
            assert error.value.code=='SMS_RESULT_PENDING'
        finally:release.set()
        assert pending.result(timeout=2)['smsCode']=='445566'
    assert provider.calls==1 and provider.get_status_calls==1
    assert not any(status==8 for _,status in provider.set_status_calls)
    assert s.db.scalar('SELECT IS_FREE_LOCK(?)','smsinvit:sms:'+sid)==1
