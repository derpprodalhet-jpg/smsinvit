class CancelCountingProvider(SmsProvider):
    def __init__(self):
        super().__init__();self.set_status_calls=[];self.get_status_calls=0
    def set_status(self,aid,status):
        with self.lock:
            self.set_status_calls.append((aid,status))
            return 'ACCESS_CANCEL' if status==8 else 'ACCESS_RETRY_GET'
    def get_status(self,aid):
        with self.lock:self.get_status_calls+=1
        return StatusResult('WAIT')

